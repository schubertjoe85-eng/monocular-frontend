// Bundles the on-phone renderer (page.js + engine.js + the vendored three.js /
// path tracer copied from Monocular Desktop) into one self-contained HTML
// string at ../localRenderHtml.js, which LocalRenderScreen loads into a WebView.
//
//   npm run build:local-render
//
// Re-run after changing anything in this folder. The vendored path tracer
// carries Monocular's local patches - copy it from the desktop repo, never
// from npm.
import { build } from "esbuild";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const v = p => path.join(here, "vendor", p);

const result = await build({
  entryPoints: [path.join(here, "page.js")],
  bundle: true,
  format: "iife",
  minify: true,
  target: "safari15",
  write: false,
  logLevel: "warning",
  plugins: [{
    name: "vendored",
    setup(b) {
      const fixed = {
        "three": v("three/build/three.module.js"),
        "three-mesh-bvh": v("pathtracer/bvh.module.js"),
        "three-gpu-pathtracer": v("pathtracer/index.module.js"),
        "mp4-muxer": v("mp4/mp4-muxer.mjs"),
      };
      b.onResolve({ filter: /^(three|three-mesh-bvh|three-gpu-pathtracer|mp4-muxer)$/ }, a => ({ path: fixed[a.path] }));
      b.onResolve({ filter: /^three\/(addons|examples\/jsm)\// }, a => ({
        path: v("three/examples/jsm/" + a.path.replace(/^three\/(addons|examples\/jsm)\//, "")),
      }));
    },
  }],
});

const js = result.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
const html = fs.readFileSync(path.join(here, "page.html"), "utf8").replace("/*__BUNDLE__*/", () => js);
const out = path.join(here, "..", "localRenderHtml.js");
fs.writeFileSync(out,
  "// GENERATED by local-render/build.mjs - do not edit by hand.\n" +
  "export default " + JSON.stringify(html) + ";\n");
console.log(`wrote ${path.relative(process.cwd(), out)} (${(html.length / 1024).toFixed(0)} KB)`);
